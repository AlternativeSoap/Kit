/**
 * Builds src/catalog/data/popular-sites.json (~2000 real domains).
 * Source: curated multi-category seed (no network fetch; Pages builds stay offline).
 * Re-run: npm run catalog:generate
 */
import { writeFileSync, mkdirSync, readFileSync, existsSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
const OUT = join(ROOT, "src", "catalog", "data", "popular-sites.json");
const SEED_FILE = join(ROOT, "scripts", "data", "domain-seed.txt");
const TARGET = 2000;

type Row = { domain: string; rank: number; category?: string };

function normalizeDomain(raw: string): string | null {
  let d = raw.trim().toLowerCase();
  if (!d || d.startsWith("#")) return null;
  d = d.replace(/^https?:\/\//, "");
  d = d.split("/")[0] ?? "";
  d = d.replace(/^www\./, "");
  if (!d.includes(".") || d.length > 80) return null;
  return d;
}

function loadSeed(): string[] {
  const fromFile = existsSync(SEED_FILE)
    ? readFileSync(SEED_FILE, "utf8").split(/\r?\n/)
    : [];
  const inline = INLINE_SEED.split(/\r?\n/);
  return [...fromFile, ...inline];
}

function buildRows(): Row[] {
  const seen = new Set<string>();
  const rows: Row[] = [];
  for (const line of loadSeed()) {
    const domain = normalizeDomain(line);
    if (!domain || seen.has(domain)) continue;
    seen.add(domain);
    rows.push({ domain, rank: rows.length + 1 });
    if (rows.length >= TARGET) break;
  }
  return rows;
}

function main() {
  mkdirSync(dirname(OUT), { recursive: true });
  const rows = buildRows();
  if (rows.length < 1500) {
    console.warn(
      `Warning: only ${rows.length} domains (want ~${TARGET}). Expand scripts/data/domain-seed.txt`,
    );
  }
  const payload = {
    generatedAt: new Date().toISOString().slice(0, 10),
    source: "curated-seed",
    count: rows.length,
    sites: rows,
  };
  writeFileSync(OUT, `${JSON.stringify(payload)}\n`, "utf8");
  console.log(`Wrote ${rows.length} sites to ${OUT}`);
}

