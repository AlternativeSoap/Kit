export function climateLabel(id: ClimateBand, da: boolean): string {
  const row = CLIMATE_BANDS.find((c) => c.id === id);
  return da ? row?.nameDa ?? id : row?.nameEn ?? id;
}

export function matchesBiome(b: Biome, query: string): boolean {
  const q = query.trim().toLowerCase();
  if (!q) return true;
  return (
    b.nameDa.toLowerCase().includes(q) ||
    b.nameEn.toLowerCase().includes(q) ||
    b.plantsDa.toLowerCase().includes(q) ||
    b.plantsEn.toLowerCase().includes(q) ||
    b.animalsDa.toLowerCase().includes(q) ||
    b.animalsEn.toLowerCase().includes(q)
  );
}
