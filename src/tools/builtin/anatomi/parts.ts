export function matchesPart(p: BodyPart, query: string): boolean {
  const q = query.trim().toLowerCase();
  if (!q) return true;
  return (
    p.id.includes(q) ||
    p.nameDa.toLowerCase().includes(q) ||
    p.nameEn.toLowerCase().includes(q) ||
    (p.latin?.toLowerCase().includes(q) ?? false) ||
    p.functionDa.toLowerCase().includes(q) ||
    p.functionEn.toLowerCase().includes(q)
  );
}
