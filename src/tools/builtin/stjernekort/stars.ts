export function matchesStar(star: Star, query: string): boolean {
  const q = query.trim().toLowerCase();
  if (!q) return true;
  if (star.nameDa.toLowerCase().includes(q)) return true;
  if (star.nameEn.toLowerCase().includes(q)) return true;
  if (star.id.toLowerCase().includes(q)) return true;
  const c = CONSTELLATIONS.find((x) => x.id === star.constellationId);
  if (c) {
    if (c.nameDa.toLowerCase().includes(q)) return true;
    if (c.nameEn.toLowerCase().includes(q)) return true;
  }
  return false;
}

export function constellationOf(star: Star): Constellation | undefined {
  return CONSTELLATIONS.find((c) => c.id === star.constellationId);
}

/** Northern polar-style map: Polaris near center, RA around the rim. */
export function projectStar(
  star: Star,
  size: number,
): { x: number; y: number; visible: boolean } {
  const cx = size / 2;
  const cy = size / 2;
  const maxR = size / 2 - 12;
  // Co-declination from north pole
  const coDec = 90 - star.dec;
  if (coDec > 115) {
    // Far southern: park near rim faintly / still show for bright stars
  }
  const r = Math.min(maxR, (coDec / 100) * maxR);
  const theta = ((star.ra / 24) * 2 - 0.5) * Math.PI; // 0h at bottom-ish
  return {
    x: cx + r * Math.sin(theta),
    y: cy - r * Math.cos(theta),
    visible: star.dec > -40,
  };
}
