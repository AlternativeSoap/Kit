export const UUID_MIN_COUNT = 1;
export const UUID_MAX_COUNT = 50;
export const UUID_DEFAULT_COUNT = 5;

export function generateUuid(): string {
  if (typeof crypto.randomUUID === "function") {
    return crypto.randomUUID();
  }
  const bytes = new Uint8Array(16);
  crypto.getRandomValues(bytes);
  bytes[6] = (bytes[6]! & 0x0f) | 0x40;
  bytes[8] = (bytes[8]! & 0x3f) | 0x80;
  const hex = Array.from(bytes, (byte) => byte.toString(16).padStart(2, "0")).join("");
  return `${hex.slice(0, 8)}-${hex.slice(8, 12)}-${hex.slice(12, 16)}-${hex.slice(16, 20)}-${hex.slice(20)}`;
}

export function generateUuids(count: number): string[] {
  const n = Math.min(UUID_MAX_COUNT, Math.max(UUID_MIN_COUNT, Math.floor(count)));
  return Array.from({ length: n }, () => generateUuid());
}